export function pickWallNote(last?: string): string {
  let n = wallNotes[Math.floor(Math.random() * wallNotes.length)];
  let guard = 0;
  while (n === last && guard++ < 8) {
    n = wallNotes[Math.floor(Math.random() * wallNotes.length)];
  }
  return n;
}
