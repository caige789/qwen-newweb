function pick<T>(arr: T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

const MOOD_WORDS = ["累", "泪", "慌", "独", "眠", "念", "雾", "火", "班", "卷", "雨", "暖"];

/** 从一句话里识别心情，用于放飞天灯（只取一个字，不带走原话） */
export function detectMood(input: string): string {
  const text = input.trim().toLowerCase();
  if (!text) return "安";
  for (let gi = 0; gi < poemGroups.length; gi++) {
    if (poemGroups[gi].keys.some((k) => text.includes(k.toLowerCase()))) {
      return MOOD_WORDS[gi] ?? "安";
    }
  }
  return "安";
}

/** 根据输入匹配一句回应 */
export function replyTo(input: string): string {
  const text = input.trim().toLowerCase();
  if (!text) return pick(generalLines);
  const matched = poemGroups.find((g) => g.keys.some((k) => text.includes(k.toLowerCase())));
  if (matched) {
    if (Math.random() < 0.35) return pick(generalLines);
    return pick(matched.lines);
  }
  return pick(generalLines);
}

