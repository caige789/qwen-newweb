let lastFortune = -1;

/** 每日一签：以日期为种子，同一天永远是同一支（刷新不变） */
export function drawDailyFortune(d: Date = new Date()): Fortune {
  const seed = d.getFullYear() * 10000 + (d.getMonth() + 1) * 100 + d.getDate();
  return fortunes[seed % fortunes.length];
}

/** 摇一支签（避免连续摇到同一支） */
export function drawFortune(): Fortune {
  let i = Math.floor(Math.random() * fortunes.length);
  if (i === lastFortune) i = (i + 1) % fortunes.length;
  lastFortune = i;
  return fortunes[i];
}
