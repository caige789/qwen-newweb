/** 随机挑一句，避免和上一句重复 */
export function pickBottleNote(last?: string): string {
  if (bottleNotes.length === 0) return "";
  let n = bottleNotes[Math.floor(Math.random() * bottleNotes.length)];
  let guard = 0;
  while (n === last && guard++ < 6) {
    n = bottleNotes[Math.floor(Math.random() * bottleNotes.length)];
  }
  return n;
}
